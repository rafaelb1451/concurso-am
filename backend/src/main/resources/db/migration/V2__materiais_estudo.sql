--
-- Material de estudo publico (CREA-AM e futuros certames).
-- Conteudo em texto puro; seed idempotente por slug em classpath:materiais.json.
--

CREATE TABLE public.materiais_estudo (
    id bigint NOT NULL,
    concurso character varying(20) NOT NULL,
    slug character varying(160) NOT NULL,
    titulo character varying(200) NOT NULL,
    resumo text,
    categoria character varying(20) NOT NULL,
    fonte character varying(200),
    conteudo text,
    ordem integer NOT NULL,
    atualizado_em timestamp(6) with time zone NOT NULL
);

ALTER TABLE public.materiais_estudo ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (
    SEQUENCE NAME public.materiais_estudo_id_seq
    START WITH 1
    INCREMENT BY 1
    NO MINVALUE
    NO MAXVALUE
    CACHE 1
);

ALTER TABLE ONLY public.materiais_estudo
    ADD CONSTRAINT materiais_estudo_pkey PRIMARY KEY (id);

ALTER TABLE ONLY public.materiais_estudo
    ADD CONSTRAINT uk_materiais_estudo_slug UNIQUE (slug);

CREATE INDEX idx_materiais_estudo_concurso ON public.materiais_estudo USING btree (concurso, ordem);
