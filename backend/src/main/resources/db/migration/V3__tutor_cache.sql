--
-- Cache de respostas do tutor virtual.
--
-- A chave e' o SHA-256 hex do JSON canonico de {contexto, mensagens}; nenhum dado do
-- usuario entra na chave. Respostas vazias e falhas do provedor nao sao gravadas.
--

CREATE TABLE public.tutor_cache (
    id bigint NOT NULL,
    chave character varying(64) NOT NULL,
    resposta text NOT NULL,
    criada_em timestamp(6) with time zone NOT NULL,
    acessos integer DEFAULT 0 NOT NULL
);

--
-- Name: tutor_cache_id_seq; Type: SEQUENCE; Schema: public; Owner: -
--

ALTER TABLE public.tutor_cache ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (
    SEQUENCE NAME public.tutor_cache_id_seq
    START WITH 1
    INCREMENT BY 1
    NO MINVALUE
    NO MAXVALUE
    CACHE 1
);

--
-- Name: tutor_cache tutor_cache_pkey; Type: CONSTRAINT; Schema: public; Owner: -
--

ALTER TABLE ONLY public.tutor_cache
    ADD CONSTRAINT tutor_cache_pkey PRIMARY KEY (id);

--
-- Name: tutor_cache uk_tutor_cache_chave; Type: CONSTRAINT; Schema: public; Owner: -
--

ALTER TABLE ONLY public.tutor_cache
    ADD CONSTRAINT uk_tutor_cache_chave UNIQUE (chave);
